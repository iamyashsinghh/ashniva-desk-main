-- Role keys are unique per organization, and system roles (organization_id IS NULL) are unique
-- globally. A plain UNIQUE(organization_id, key) would not work because NULLs never collide, so
-- two partial unique indexes enforce the rule (Architecture Plan §18).
CREATE UNIQUE INDEX "ux_roles_org_key" ON "roles" ("organization_id", "key") WHERE "organization_id" IS NOT NULL;
CREATE UNIQUE INDEX "ux_roles_system_key" ON "roles" ("key") WHERE "organization_id" IS NULL;

-- Exactly one organization is the service provider (the company running Ashniva Desk).
CREATE UNIQUE INDEX "ux_organizations_service_provider" ON "organizations" ("is_service_provider") WHERE "is_service_provider" = TRUE;
